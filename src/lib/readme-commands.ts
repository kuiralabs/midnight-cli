// The README's table of commands, from the command registry: one row per
// command help lists, in help's order, with its help's usage and
// description. scripts/write-readme-commands.ts writes it between the
// README's markers; a test fails when the README differs.

import type { CommandRegistry } from '@kuiralabs/midnight-cli-core';

/** The markers around the generated table in README.md. */
export const README_COMMANDS_START = '<!-- commands: generated by npm run readme-commands -->';
export const README_COMMANDS_END = '<!-- commands: end -->';

/** The table, as markdown, ending with a newline. */
export function readmeCommandTable(registry: Pick<CommandRegistry, 'commands'>): string {
  // A pipe splits a table cell, inside a code span too, unless escaped.
  const cell = (text: string): string => text.replaceAll('|', '\\|');
  const rows = registry.commands.flatMap((command) =>
    command.help === undefined ? [] : [`| \`${cell(command.help.usage)}\` | ${cell(command.help.description)} |`]);
  return ['| Command | Description |', '|---------|-------------|', ...rows].join('\n') + '\n';
}

/** `doc` (the file `name`) with what is between its markers `startMarker` and `endMarker` replaced by `content`. */
export function withGeneratedBlock(doc: string, name: string, startMarker: string, endMarker: string, content: string): string {
  const start = doc.indexOf(startMarker);
  const end = doc.indexOf(endMarker);
  if (start === -1 || end < start) throw new Error(`${name} has no ${startMarker} … ${endMarker} markers`);
  return doc.slice(0, start + startMarker.length) + '\n' + content + doc.slice(end);
}

/** The README with the table between its markers replaced by `table`. */
export function withReadmeCommandTable(readme: string, table: string): string {
  return withGeneratedBlock(readme, 'README.md', README_COMMANDS_START, README_COMMANDS_END, table);
}
