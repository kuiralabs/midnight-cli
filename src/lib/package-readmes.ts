// The public packages' READMEs: each package's table of the error codes it
// owns, from its code definitions, between the README's markers.
// scripts/write-package-readmes.ts writes them; a test fails when a README
// differs, and runs each README's mounting example as it is written.

import type { CodeDefinition } from '@kuiralabs/midnight-cli-core';
import { coreCodes } from '@kuiralabs/midnight-cli-core/commands';
import { chainCodes } from '@kuiralabs/midnight-chain/commands';
import { walletCodes } from '@kuiralabs/midnight-wallet/commands';
import { contractCodes } from '@kuiralabs/midnight-contract/commands';
import { devCodes } from '@kuiralabs/midnight-dev/commands';
import { grantCodes } from '@kuiralabs/midnight-grant/commands';
import { connectCodes } from '@kuiralabs/midnight-connect/commands';
import { withGeneratedBlock } from './readme-commands.ts';

/** The markers around a package README's table of codes. */
export const README_CODES_START = '<!-- codes: generated by npm run package-readmes -->';
export const README_CODES_END = '<!-- codes: end -->';

/** The codes each public package owns, by its folder under packages/; a package that owns none is absent. */
export const PACKAGE_CODES: Readonly<Record<string, readonly CodeDefinition[]>> = {
  'cli-core': coreCodes,
  chain: chainCodes,
  wallet: walletCodes,
  contract: contractCodes,
  connect: connectCodes,
  dev: devCodes,
  grant: grantCodes,
};

/** The table of `codes`, in their tables' order, as markdown ending with a newline. */
export function packageCodeTable(codes: readonly CodeDefinition[]): string {
  const cell = (text: string): string => text.replaceAll('|', '\\|').replaceAll('\n', ' ');
  const ordered = [...codes].sort((a, b) => (a.order ?? Number.MAX_SAFE_INTEGER) - (b.order ?? Number.MAX_SAFE_INTEGER) || a.code.localeCompare(b.code));
  const rows = ordered.map((c) => `| \`${c.code}\` | ${c.exitCode} | ${cell(c.summary)} | ${cell(c.recovery ?? '')} |`);
  return ['| Code | Exit | What went wrong | What to do |', '|------|------|-----------------|------------|', ...rows].join('\n') + '\n';
}

/** The README `readme` (of the package in `dir`) with its table of codes written between its markers. */
export function withPackageCodeTable(readme: string, dir: string, codes: readonly CodeDefinition[]): string {
  return withGeneratedBlock(readme, `packages/${dir}/README.md`, README_CODES_START, README_CODES_END, packageCodeTable(codes));
}
