// The tables of error codes that are not agent guidance, from the installed
// packages' code definitions: docs/JSON_CONTRACT.md's, which
// scripts/write-readme-commands.ts writes between its markers (a test fails
// when the file differs), and the lines of `mn manual`'s EXIT CODES block.
// The manual's and the skills' rows come from each package's guidance
// (codeGuidancePieces).

import type { CommandRegistry } from '@kuiralabs/midnight-cli-core/lib/command-definition';
import type { CodeDefinition } from '@kuiralabs/midnight-cli-core/lib/error-codes';
import { wrapWords } from '@kuiralabs/midnight-cli-core/lib/agent-guidance';
import { withGeneratedBlock } from './readme-commands.ts';

/** The markers around the generated table in docs/JSON_CONTRACT.md. */
export const JSON_CONTRACT_CODES_START = '<!-- error codes: generated by npm run readme-commands -->';
export const JSON_CONTRACT_CODES_END = '<!-- error codes: end -->';

/** Every installed package's codes, in their order (a code with none after those that have one, as installed). */
export function installedCodes(registry: Pick<CommandRegistry, 'packages'>): CodeDefinition[] {
  const codes = registry.packages.flatMap((pkg) => pkg.codes ?? []);
  const place = (definition: CodeDefinition): number => definition.order ?? Number.POSITIVE_INFINITY;
  return codes.map((definition, at) => ({ definition, at }))
    .sort((a, b) => place(a.definition) - place(b.definition) || a.at - b.at)
    .map(({ definition }) => definition);
}

/** docs/JSON_CONTRACT.md's table of error codes, as markdown ending with a newline. */
export function jsonContractCodeTable(registry: Pick<CommandRegistry, 'packages'>): string {
  // A pipe splits a table cell, inside a code span too, unless escaped.
  const cell = (text: string): string => text.replaceAll('|', '\\|');
  const rows = installedCodes(registry).map(({ code, exitCode, summary }) => `| \`${code}\` | ${exitCode} | ${cell(summary)} |`);
  return ['| Code | Exit | Meaning |', '|------|------|---------|', ...rows].join('\n') + '\n';
}

/** docs/JSON_CONTRACT.md with the table between its markers replaced by `table`. */
export function withJsonContractCodeTable(doc: string, table: string): string {
  return withGeneratedBlock(doc, 'docs/JSON_CONTRACT.md', JSON_CONTRACT_CODES_START, JSON_CONTRACT_CODES_END, table);
}

// `mn manual`'s list: the code in a column of 31 (the longest code is 30), its
// exit code, then the meaning from column 38 of an 80-column page.
const MANUAL_CODE_INDENT = 4;
const MANUAL_CODE_COLUMN = 31;
const MANUAL_MEANING_COLUMN = 38;
const MANUAL_WIDTH = 80;

/** One line or more per installed code for `mn manual`: code, exit code, meaning; `styleCode` colours the code. */
export function manualCodeLines(registry: Pick<CommandRegistry, 'packages'>, styleCode: (code: string) => string = (code) => code): string[] {
  return installedCodes(registry).flatMap(({ code, exitCode, summary }) => {
    const [first = '', ...rest] = wrapWords(summary, MANUAL_WIDTH - MANUAL_MEANING_COLUMN);
    const head = `${' '.repeat(MANUAL_CODE_INDENT)}${styleCode(code)}${' '.repeat(Math.max(1, MANUAL_CODE_COLUMN - code.length))}${exitCode}  `;
    return [head + first, ...rest.map((line) => ' '.repeat(MANUAL_MEANING_COLUMN) + line)];
  });
}
